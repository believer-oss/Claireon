#pragma once

#include "Tools/IClaireonTool.h"

/**
 * MCP tool: datatable_composite_refresh
 * Refresh the cached row map of a composite data table and save it. Immediate and
 * non-session: rebuild and save both happen in one call under a scoped asset lock.
 */
class ClaireonTool_DataTableCompositeRefresh : public IClaireonTool
{
public:
	virtual FString GetCategory() const override;
	virtual FString GetOperation() const override;
	virtual bool RequiresNoPIE() const override { return true; }
	virtual EClaireonToolSessionMode GetSessionMode() const override { return EClaireonToolSessionMode::RequiresSession; }
	virtual FString GetDescription() const override;
	virtual TSharedPtr<FJsonObject> GetInputSchema() const override;
	virtual FToolResult Execute(const TSharedPtr<FJsonObject>& Arguments) override;
};
